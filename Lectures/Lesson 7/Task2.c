#include<stdio.h>

int main() {

    int h=5;
    int length=h*2-1;

    for (int i=h; i>=0; i--) {

        for (int j=i; j=(h-j-1); j--) {
            printf("   ", j);
        }

        for (int k=0; k=i; k++) {
            printf(" * ", k);
        }

        for (int j=i; j=(h-j-1); j--) {
            printf("   ", j);
        }

    }

}